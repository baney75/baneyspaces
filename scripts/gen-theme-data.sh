#!/bin/bash
# Embeds spec/themes.json and spec/palettes.json in the app as Swift strings
# (Sources/BaneySpacesCore/ThemeData.swift), so the app needs no resource bundle to find them.
# `swift test` fails (ThemeDataTests) when the embedded copy and spec/ differ: run this after
# changing either spec file.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Sources/BaneySpacesCore/ThemeData.swift
{
  echo "// Generated by scripts/gen-theme-data.sh from spec/themes.json and spec/palettes.json. Do not edit."
  echo "public enum ThemeData {"
  echo '    public static let themesJSON = #"""'
  cat spec/themes.json
  echo '"""#'
  echo
  echo '    public static let palettesJSON = #"""'
  cat spec/palettes.json
  echo '"""#'
  echo "}"
} > "$OUT"
echo "wrote $OUT"
