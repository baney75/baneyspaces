#!/bin/bash
# Writes Sources/BaneySpacesCore/SitesData.swift from spec/sites.json, the one site list every platform
# shares (spec/launcher.md). SitesDataTests fails when the two differ.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import json
d = json.load(open("spec/sites.json"))
def q(s): return json.dumps(s, ensure_ascii=False)
rows = []
for s in d["sites"]:
    rows.append("        .init(id: %s, name: %s, url: %s, aliases: [%s], native: [%s], iphone: %s)," % (
        q(s["id"]), q(s["name"]), q(s["url"]), ", ".join(q(a) for a in s["aliases"]),
        ", ".join(q(a) for a in s.get("native", [])), q(s["iphone"]) if "iphone" in s else "nil"))
open("Sources/BaneySpacesCore/SitesData.swift", "w").write(
"""// Generated by scripts/gen-sites-data.sh from spec/sites.json. Do not edit.
import Foundation

extension SiteCatalog {
    /// The built-in sites, in spec/sites.json's order.
    public static let entries: [Entry] = [
%s
    ]
}
""" % "\n".join(rows))
PY
