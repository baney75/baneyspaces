#!/bin/bash
# Embeds spec/devices.json in the app as a Swift string (Sources/BaneySpacesCore/DeviceData.swift),
# so the app needs no resource bundle to find it. `swift test` fails (DevicesTests) when the
# embedded copy and spec/ differ: run this after changing the spec file.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Sources/BaneySpacesCore/DeviceData.swift
{
  echo "// Generated by scripts/gen-device-data.sh from spec/devices.json. Do not edit."
  echo "public enum DeviceData {"
  echo '    public static let devicesJSON = #"""'
  cat spec/devices.json
  echo '"""#'
  echo "}"
} > "$OUT"
echo "wrote $OUT"
